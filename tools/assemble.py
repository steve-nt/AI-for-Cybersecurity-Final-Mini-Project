"""Build the single hand-in notebook from the part notebooks.

The work is split into one notebook per part in parts/. The first line of every cell names its step:

    code cells:      # STEP A4          or  # STANDIN B2
    Markdown cells:  <!-- STEP A4 -->   or  <!-- STANDIN B2 -->

This script reads parts/*.ipynb in name order, drops the STANDIN cells (copies of a step that lives
in another part notebook) and empty cells, sorts the rest by step in two phases, keeps the notebook
order inside one step, and writes mini_project_unsw_nb15.ipynb with a title cell:

    development: A0 ... A4, B1, B2, C1 ... C3, X2, D1, F1 ... F3
                 every setting is chosen here, on the validation set; the test set is sealed (end of A3)
    T0:          every setting is fixed; the test set is opened
    evaluation:  A4T, B3, B4, C4, D2 ... D6, E1 ... E4, F3T, F4, F5, G1 ... G4, X2T, X3 ... X9

A step ending in T is the test-set half of a step whose settings are chosen in the development phase
(A4T, F3T, X2T). The additional checks
(X steps) are part of the hand-in notebook, because the report quotes their results; --without-extras
leaves them out for a quicker run. It then executes the notebook from the repository root, so that it
runs top to bottom exactly as the brief requires.

Usage (from anywhere, with the project environment active):
    python tools/assemble.py                # build and execute
    python tools/assemble.py --no-execute   # build only (quick check of markers and order)
    python tools/assemble.py --strict       # also fail if a step A0-G4 is missing, or if a cell
                                            # between the seal (A3) and T0 uses the test set (hand-in)
    python tools/assemble.py --without-extras  # leave out the additional checks X1-X9 (quicker)
"""

import argparse
import re
import sys
import uuid
from pathlib import Path

import nbformat

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "mini_project_unsw_nb15.ipynb"

# Two phases. Development: A0 is the shared setup (install, imports, helpers), then every step that
# chooses a setting, on the validation set; the test set is sealed at the end of A3. T0 opens it. Evaluation:
# every step that scores on the test set, in the order of Parts A-G, then the additional checks.
DEVELOPMENT = ["A0", "A1", "A2", "A3", "A4", "B1", "B2", "C1", "C2", "C3", "X2", "D1", "F1", "F2", "F3"]
EVALUATION = (["T0", "A4T", "B3", "B4", "C4", "D2", "D3", "D4", "D5", "D6", "E1", "E2", "E3", "E4",
               "F3T", "F4", "F5", "G1", "G2", "G3", "G4", "X1", "X2T"] + [f"X{i}" for i in range(3, 10)])
STEP_ORDER = DEVELOPMENT + EVALUATION
LAB_STEPS = [s for s in STEP_ORDER if not s.startswith("X")]
TEST_NAMES = re.compile(r"\b(X_test|y_test|type_test|_SEALED_TEST)\b")
RANK = {step: i for i, step in enumerate(STEP_ORDER)}

CODE_MARKER = re.compile(r"^#\s*(STEP|STANDIN)\b\s*(.*)$")
MD_MARKER = re.compile(r"^<!--\s*(STEP|STANDIN)\b\s*(.*?)\s*-->")

TITLE = """# Mini Project: An Explainable and Robust Cyber-Defence Model

AI for Cybersecurity (D7084E / D7041E)
Kirill Silchenko (kirsil-5@student.ltu.se) and Stefanos Ntentopoulos (stente-5@student.ltu.se)

Is a network flow an attack or normal traffic? A detector trained on all 305,105 clean flows of
CIC-UNSW-NB15 (UNSW-NB15 with CICFlowMeter features), and Parts A-G of the brief in order: the problem,
the data and the always-benign baseline (A), a decision tree, logistic regression and gradient boosting
(B), learning with 10% of the labels and pseudo-labelling (C), SHAP and LIME explanations with fidelity
and stability checks (D), noise and missing features (E), a belief rule base on the two most important
features (F), and an attack type hidden from training and then adapted to (G). At the end, additional
checks of these results (steps X2 to X9), which the report also quotes.

**Two phases.** The notebook first makes every choice, on the validation set: the model settings (B1,
B2), the pseudo-labelling cutoffs (C2, X2), the BRB's features and threshold (F1, F2) and the depth of
the two-feature tree (F3). Until then the test set is sealed (end of step A3): only its size and row
numbers are known. Step T0 opens it, and from there on the notebook only reports scores on it, in the
order of Parts A to G. `random_state=42` throughout. Run from top to bottom; the data are `UNSW-NB15/Data.csv` and `UNSW-NB15/Label.csv` (see `README.md`).

*Generated by `tools/assemble.py` from the notebooks in `parts/`. Do not edit this file by hand.*"""


class MarkerError(Exception):
    pass


def read_marker(cell):
    """Return (kind, argument) from the cell's first non-empty line; kind is STEP or STANDIN."""
    lines = [line.strip() for line in cell.source.splitlines() if line.strip()]
    if not lines:
        return None, None
    pattern = CODE_MARKER if cell.cell_type == "code" else MD_MARKER
    match = pattern.match(lines[0])
    if not match:
        return None, lines[0]
    return match.group(1), match.group(2).strip()


def collect(parts_dir, with_extras=True):
    """Read every part notebook and return (sorted cells, problems, steps seen per file)."""
    kept, problems, sources = [], [], {}
    files = sorted(parts_dir.glob("*.ipynb"))
    if not files:
        raise MarkerError(f"no notebooks found in {parts_dir}")

    for file_no, path in enumerate(files):
        nb = nbformat.read(path, as_version=4)
        for cell_no, cell in enumerate(nb.cells, start=1):
            if cell.cell_type not in ("code", "markdown"):
                continue
            kind, arg = read_marker(cell)
            where = f"{path.name}, cell {cell_no}"
            if kind is None and arg is None:
                continue                                  # empty cell
            if kind is None:
                problems.append(f"{where}: no step marker; first line is: {arg[:70]!r}")
            elif kind == "STANDIN":
                continue                                  # the real step fills the gap
            elif arg not in RANK:
                problems.append(f"{where}: unknown step {arg!r} (expected one of "
                                f"{', '.join(STEP_ORDER)})")
            else:
                if arg.startswith("X") and not with_extras:
                    continue                              # additional check, left out on request
                kept.append((RANK[arg], file_no, cell_no, cell))
                sources.setdefault(arg, set()).add(path.name)

    kept.sort(key=lambda item: item[:3])                 # step, then file, then position
    return [item[3] for item in kept], problems, sources


def clean(cell):
    """A copy of the cell without outputs, execution counts or old ids."""
    new = nbformat.from_dict(dict(cell))
    new["id"] = uuid.uuid4().hex[:8]                      # ids from different parts may clash
    new["metadata"] = {}
    if new.cell_type == "code":
        new["outputs"], new["execution_count"] = [], None
    return new


def build(cells):
    nb = nbformat.v4.new_notebook(metadata={
        "kernelspec": {"name": "python3", "display_name": "Python 3", "language": "python"},
        "language_info": {"name": "python"},
    })
    nb.cells = [nbformat.v4.new_markdown_cell(TITLE)] + [clean(c) for c in cells]
    nb.cells[0]["id"] = "title"
    return nb


def execute(nb, output):
    from nbconvert.preprocessors import CellExecutionError, ExecutePreprocessor

    runner = ExecutePreprocessor(timeout=3600, kernel_name="python3")
    try:
        runner.preprocess(nb, {"metadata": {"path": str(ROOT)}})
    except CellExecutionError as error:
        nbformat.write(nb, output)                        # keep the outputs up to the error
        print(f"\nExecution FAILED; the notebook with outputs up to the error is in {output.name}")
        print(str(error)[-1500:])
        return False
    nbformat.write(nb, output)
    return True


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--parts", type=Path, default=ROOT / "parts", help="folder with the part notebooks")
    parser.add_argument("--output", type=Path, default=OUTPUT, help="notebook to write")
    parser.add_argument("--no-execute", action="store_true", help="only build, do not run the notebook")
    parser.add_argument("--strict", action="store_true", help="fail if a step A0-G4 is missing")
    parser.add_argument("--without-extras", action="store_true",
                        help="leave out the additional checks X1-X9 (included by default)")
    args = parser.parse_args()

    try:
        cells, problems, sources = collect(args.parts, not args.without_extras)
    except MarkerError as error:
        sys.exit(f"ERROR: {error}")
    if problems:
        print("ERROR: fix these cells first (every cell needs '# STEP <id>' or '# STANDIN <id>'):")
        print("\n".join(f"  - {p}" for p in problems))
        sys.exit(1)

    print("Steps found (step: part notebook):")
    for step in STEP_ORDER:
        if step in sources:
            print(f"  {step:4s} {', '.join(sorted(sources[step]))}")
    for step, files in sources.items():
        if len(files) > 1:
            print(f"WARNING: step {step} comes from more than one notebook: {', '.join(sorted(files))}")
    missing = [s for s in LAB_STEPS if s not in sources]
    if missing:
        print(f"Missing lab steps ({len(missing)}): {' '.join(missing)}")
        if args.strict:
            sys.exit("ERROR: --strict: every step A0-G4 must be present for the hand-in")
    if args.strict:
        # The test set is sealed at the end of the last A3 cell and opened in T0: no code cell in between
        # may use it. (Running the notebook checks the same: those names do not exist there.)
        steps = [read_marker(c)[1] for c in cells]
        start = max(i for i, step in enumerate(steps) if step == "A3") + 1
        end = steps.index("T0")
        leaks = [f"{steps[i]}: {cells[i].source.splitlines()[0]}" for i in range(start, end)
                 if cells[i].cell_type == "code" and TEST_NAMES.search(cells[i].source)]
        if leaks:
            sys.exit("ERROR: --strict: these cells use the test set before T0:\n  " + "\n  ".join(leaks))
        print(f"Test set: sealed after cell {start} of {len(cells)}, opened at T0 (cell {end}); "
              f"no code cell in between uses it.")

    nb = build(cells)
    nbformat.validate(nb)
    nbformat.write(nb, args.output)
    print(f"Wrote {args.output.relative_to(ROOT) if args.output.is_relative_to(ROOT) else args.output} "
          f"({len(nb.cells)} cells)")

    if args.no_execute:
        return
    print("Executing from the repository root ...")
    if not execute(nb, args.output):
        sys.exit(1)
    print("Executed top to bottom without errors.")


if __name__ == "__main__":
    main()
